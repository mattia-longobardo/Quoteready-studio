import { NextResponse } from "next/server";

import { sanitizeBlobFileName } from "@quoteredy/storage";

import { isErrorResponse, requireSession } from "@/lib/api-auth";
import { archivePartCad } from "@/lib/artifacts";
import { parseAnalysisMultipart } from "@/lib/multipart";
import { savePart, updatePart } from "@/lib/platform-store";
import {
  assertSameOrigin,
  enforceRateLimit,
  inputErrorResponse,
  readResponseText,
  RequestInputError,
} from "@/lib/request-security";
import { getCadFormat, isValidCadContent } from "@/lib/rfq";
import { ZooAuthError } from "@/lib/zoo-auth";
import {
  projectsForbiddenDetail,
  resolveProjectsToken,
} from "@/lib/zoo-projects";
import { storePartModel } from "@/lib/zoo-model";

export const runtime = "nodejs";

const ZOO_PROJECTS_ENDPOINT = "https://api.zoo.dev/user/projects";
const MAX_ZOO_RESPONSE_BYTES = 256 * 1024;
// Formats a Zoo project entrypoint can import as foreign geometry; other
// analysable CAD formats cannot be referenced from one yet.
const ZOO_PROJECT_FORMATS = new Set(["step", "stl", "obj", "ply", "sldprt"]);

function sanitizeTitle(raw: string | undefined, fallback: string): string {
  const cleaned = (raw ?? "")
    .replace(/[\p{Cc}\p{Cf}"\\]/gu, "")
    .trim()
    .slice(0, 100);
  return cleaned || fallback;
}

/**
 * Entrypoint file every Zoo draft project needs: it imports the uploaded
 * geometry and returns it as the model, matching the contract used by Zoo's
 * own API clients. This is part of the Zoo project format, not a CAD
 * translation — the file is written once at upload time and never read back.
 */
function projectEntrypoint(fileName: string): string {
  return [
    "// Entrypoint generated by QuoteReady Studio for an imported CAD file.",
    `import "${fileName}" as part`,
    "",
    "part",
    "",
  ].join("\n");
}

function projectToml(title: string): string {
  return [
    `name = "${title}"`,
    `description = "Uploaded from QuoteReady Studio"`,
    "",
    "[settings.modeling]",
    `base_unit = "mm"`,
    "",
  ].join("\n");
}

export async function POST(request: Request) {
  try {
    assertSameOrigin(request);
    const session = await requireSession();
    if (isErrorResponse(session)) return session;

    enforceRateLimit(`zoo-upload:${session.user.id}`, 5, 60_000);

    const upload = await parseAnalysisMultipart(request);
    if (!upload.cadFile) {
      throw new RequestInputError(
        "Select a CAD file to upload to your Zoo library.",
      );
    }
    if (upload.drawing) {
      throw new RequestInputError(
        "Only the CAD file is uploaded to Zoo; remove the drawing attachment.",
      );
    }
    const format = getCadFormat(upload.cadFile.name);
    if (!format || !ZOO_PROJECT_FORMATS.has(format)) {
      throw new RequestInputError(
        "Zoo projects accept STEP, STL, OBJ, PLY or SLDPRT files.",
        415,
      );
    }
    if (!isValidCadContent(upload.cadFile, format)) {
      throw new RequestInputError(
        "The uploaded file content does not match the selected CAD format.",
        415,
      );
    }

    const fileName = sanitizeBlobFileName(upload.cadFile.name);
    const title = sanitizeTitle(
      upload.fields.projectName,
      fileName.replace(/\.[^.]+$/, ""),
    );

    // Part name doubles as the file path inside the draft project, matching
    // the contract used by Zoo's own API clients.
    const form = new FormData();
    form.append(
      "project.toml",
      new Blob([projectToml(title)], { type: "application/toml" }),
      "project.toml",
    );
    form.append(
      "main.kcl",
      new Blob([projectEntrypoint(fileName)], { type: "text/plain" }),
      "main.kcl",
    );
    form.append(
      fileName,
      new Blob([new Uint8Array(upload.cadFile.bytes)], {
        type: "application/octet-stream",
      }),
      fileName,
    );

    const { token, source } = await resolveProjectsToken(session);
    const response = await fetch(ZOO_PROJECTS_ENDPOINT, {
      method: "POST",
      headers: { Authorization: `Bearer ${token}` },
      body: form,
      cache: "no-store",
      signal: AbortSignal.timeout(45_000),
    });
    const text = await readResponseText(response, MAX_ZOO_RESPONSE_BYTES);

    let payload: Record<string, unknown> = {};
    try {
      payload = text ? (JSON.parse(text) as Record<string, unknown>) : {};
    } catch {
      payload = {};
    }

    if (!response.ok) {
      const detail =
        response.status === 403
          ? projectsForbiddenDetail(source)
          : typeof payload.message === "string"
            ? payload.message.slice(0, 300)
            : `HTTP ${response.status}`;
      console.warn(
        `Zoo project upload failed (${source}): HTTP ${response.status}`,
      );
      return NextResponse.json(
        { error: "Zoo could not create the project.", detail },
        { status: 502 },
      );
    }

    // Record the upload as a part so it appears in the Parts view. This is
    // best-effort bookkeeping: a store failure must not undo the Zoo upload.
    try {
      const part = await savePart(session.user.id, {
        name: title,
        fileName,
        format,
        sizeBytes: upload.cadFile.size,
        status: "uploaded",
        source: "zoo-upload",
        reportId: null,
        zooProjectId: typeof payload.id === "string" ? payload.id : null,
      });
      // Archive the CAD (for later drawing tables) and build the glTF
      // preview; both helpers are best-effort and never throw.
      const cadArrayBuffer = upload.cadFile.bytes.buffer.slice(
        upload.cadFile.bytes.byteOffset,
        upload.cadFile.bytes.byteOffset + upload.cadFile.bytes.byteLength,
      ) as ArrayBuffer;
      const [cadBlobKey, modelBlobKey] = await Promise.all([
        archivePartCad(session.user.id, part.id, upload.cadFile),
        storePartModel({
          userId: session.user.id,
          partId: part.id,
          file: cadArrayBuffer,
          format,
          token,
        }),
      ]);
      if (cadBlobKey || modelBlobKey) {
        await updatePart(session.user.id, part.id, {
          cadBlobKey,
          modelBlobKey,
        });
      }
    } catch (error) {
      console.warn(
        "Part record for Zoo upload failed:",
        error instanceof Error ? error.message : error,
      );
    }

    return NextResponse.json(
      {
        id: typeof payload.id === "string" ? payload.id : null,
        name: typeof payload.title === "string" ? payload.title : title,
        entrypoint:
          typeof payload.entrypoint_path === "string"
            ? payload.entrypoint_path
            : "main.kcl",
      },
      { status: 201 },
    );
  } catch (error) {
    if (error instanceof ZooAuthError) {
      return NextResponse.json(
        { error: error.message },
        { status: error.status },
      );
    }
    return inputErrorResponse(
      error,
      "The CAD file could not be uploaded to Zoo.",
    );
  }
}
